#!/usr/bin/env python3
"""replay.py <access.log> --a URL --b URL: replays the GETs of a PictShare access log against two
servers and compares the answers. Stdlib only, so it runs in a plain python container on the
compose network (see ../README.md, "Cutover").

Each unique path is requested once from each side, B first: a variant missing on disk is then
generated by each service itself, instead of B serving the file A just wrote. Compared: status,
content type, Location (coub/vimeo redirects), and for 200s the body (sha256); when bodies
differ, images are compared by their dimensions. Delete URLs are never replayed. Ranges are not
replayed (206 lines are requested whole); --ranges N runs RANGE_CHECKS on N of the videos instead.

Output: a summary per URL shape and outcome on stdout, every non-identical path as a JSON line
in --out. Outcomes: identical; same (same non-200 status); type-only (same bytes, other
Content-Type); same-size (image, other pixels, same dimensions); image-size, type, status,
location, body (different); error (no answer).
"""
import argparse
import collections
import hashlib
import http.client
import json
import random
import re
import ssl
import struct
import sys
import threading
import time
import urllib.parse
from concurrent.futures import ThreadPoolExecutor

LINE_RE = re.compile(r'"GET (/\S*) HTTP/[^"]*" (\d{3}) ')
HASH_RE = re.compile(r"^[A-Za-z0-9_-]+\.[A-Za-z0-9-]{2,5}$")


def paths_from_log(f):
    seen = {}
    for line in f:
        m = LINE_RE.search(line)
        if not m:
            continue
        path, status = m.group(1), m.group(2)
        if path.startswith("/api/") or status.startswith("5"):
            continue
        if "delete_" in path:  # a delete URL with a valid code deletes the file: never replayed
            continue
        seen.setdefault(path, status)
    return seen


def shape(path):
    """The URL shape for grouping: hash -> H, numbers -> N, e.g. /N/H, /preview/N/H, /H/raw."""
    out = []
    for seg in urllib.parse.urlsplit(path).path.split("/"):
        if not seg:
            continue
        if HASH_RE.match(seg) and not seg.startswith("delete_"):
            out.append("H." + seg.rsplit(".", 1)[1])
        elif re.fullmatch(r"\d+(x\d+)?", seg):
            out.append("N" if "x" not in seg else "NxN")
        elif seg.startswith("delete_"):
            out.append("delete_*")
        elif re.fullmatch(r"\w+", seg) and len(seg) <= 12:
            out.append(seg)
        else:
            out.append("?")
    return "/" + "/".join(out)


def image_size(head):
    """(w, h) of a PNG, GIF, JPEG or WebP from its first bytes, or None."""
    try:
        if head[:8] == b"\x89PNG\r\n\x1a\n":
            return struct.unpack(">II", head[16:24])
        if head[:6] in (b"GIF87a", b"GIF89a"):
            return struct.unpack("<HH", head[6:10])
        if head[:4] == b"RIFF" and head[8:12] == b"WEBP":
            kind = head[12:16]
            if kind == b"VP8 ":
                w, h = struct.unpack("<HH", head[26:30])
                return w & 0x3FFF, h & 0x3FFF
            if kind == b"VP8L":
                b = int.from_bytes(head[21:25], "little")
                return (b & 0x3FFF) + 1, ((b >> 14) & 0x3FFF) + 1
            if kind == b"VP8X":
                return int.from_bytes(head[24:27], "little") + 1, int.from_bytes(head[27:30], "little") + 1
        if head[:2] == b"\xff\xd8":
            i = 2
            while i + 9 < len(head):
                if head[i] != 0xFF:
                    i += 1
                    continue
                marker = head[i + 1]
                if marker in (0xD8, 0x01) or 0xD0 <= marker <= 0xD7 or marker == 0xFF:
                    i += 1 if marker == 0xFF else 2
                    continue
                seglen = struct.unpack(">H", head[i + 2:i + 4])[0]
                if 0xC0 <= marker <= 0xCF and marker not in (0xC4, 0xC8, 0xCC):
                    h, w = struct.unpack(">HH", head[i + 5:i + 9])
                    return w, h
                i += 2 + seglen
    except struct.error:
        pass
    return None


class Side:
    def __init__(self, base, host, insecure, rate):
        u = urllib.parse.urlsplit(base)
        self.https = u.scheme == "https"
        self.netloc = u.netloc
        self.host = host or u.hostname
        self.ctx = ssl._create_unverified_context() if insecure else ssl.create_default_context()
        self.local = threading.local()
        self.interval = 1.0 / rate if rate > 0 else 0
        self.lock = threading.Lock()
        self.next_at = 0.0

    def _conn(self):
        c = getattr(self.local, "conn", None)
        if c is None:
            if self.https:
                c = http.client.HTTPSConnection(self.netloc, timeout=300, context=self.ctx)
            else:
                c = http.client.HTTPConnection(self.netloc, timeout=300)
            self.local.conn = c
        return c

    def _throttle(self):
        if not self.interval:
            return
        with self.lock:
            now = time.monotonic()
            wait = self.next_at - now
            self.next_at = max(now, self.next_at) + self.interval
        if wait > 0:
            time.sleep(wait)

    def get(self, path, headers=None):
        self._throttle()
        for attempt in (1, 2):
            c = self._conn()
            t0 = time.monotonic()
            try:
                c.request("GET", path, headers={"Host": self.host, "User-Agent": "orbitar-media-replay", **(headers or {})})
                r = c.getresponse()
                sha, head, n = hashlib.sha256(), b"", 0
                while chunk := r.read(1 << 16):
                    sha.update(chunk)
                    if len(head) < 1 << 16:
                        head += chunk[:(1 << 16) - len(head)]
                    n += len(chunk)
                return {
                    "status": r.status,
                    "type": (r.getheader("Content-Type") or "").split(";")[0].strip(),
                    "location": r.getheader("Location") or "",
                    "range": r.getheader("Content-Range") or "",
                    "etag": r.getheader("ETag") or "",
                    "modified": r.getheader("Last-Modified") or "",
                    "len": n,
                    "sha": sha.hexdigest(),
                    "size": image_size(head),
                    "ms": round((time.monotonic() - t0) * 1000),
                }
            except (OSError, http.client.HTTPException) as e:
                c.close()
                self.local.conn = None
                if attempt == 2:
                    return {"status": 0, "error": str(e), "ms": round((time.monotonic() - t0) * 1000)}
        return None


def compare(a, b):
    if a["status"] != b["status"]:
        return "status"
    if a["status"] != 200:
        if a["status"] in (301, 302, 303, 307, 308) and a.get("location") != b.get("location"):
            return "location"
        return "same"
    if a["type"] != b["type"]:
        return "type-only" if a["sha"] == b["sha"] else "type"
    if a["sha"] == b["sha"]:
        return "identical"
    if a["size"] and a["size"] == b["size"]:
        return "same-size"
    if a["size"] or b["size"]:
        return "image-size"
    return "body"


# What Bunny (5 MB chunks) and browsers send for a video. "if-range" and "if-none-match" carry A's
# validators to B as well: a pass means a cache holding chunks from one backend can revalidate
# or continue them against the other.
CHUNK = 5 * 1024 * 1024
RANGE_CHECKS = [
    ("chunk-1", lambda v: {"Range": f"bytes=0-{CHUNK - 1}"}),
    ("chunk-2", lambda v: {"Range": f"bytes={CHUNK}-{2 * CHUNK - 1}"}),
    ("open", lambda v: {"Range": "bytes=1000-"}),
    ("suffix", lambda v: {"Range": "bytes=-500000"}),
    ("unsatisfiable", lambda v: {"Range": "bytes=999999999-"}),
    ("if-range", lambda v: {"Range": "bytes=0-99", "If-Range": v["etag"]}),
    ("if-none-match", lambda v: {"If-None-Match": v["etag"]}),
    ("if-modified-since", lambda v: {"If-Modified-Since": v["modified"]}),
]


def is_raw_video(path):
    return shape(path) in ("/H.mp4/raw", "/raw/H.mp4")


def range_checks(path, A, B):
    """[(check, outcome, a, b)] for one video; also whether both sides send the same validators."""
    full = A.get(path)
    if full["status"] != 200:
        return []
    out = []
    for name, hdrs in RANGE_CHECKS:
        h = hdrs(full)
        b, a = B.get(path, h), A.get(path, h)
        if not a["status"] or not b["status"]:
            outcome = "error"
        elif a["status"] == b["status"] == 416 and a["range"] == b["range"]:
            outcome = "identical"  # the error body (empty vs a short text) doesn't matter
        elif (a["status"], a["range"], a["len"], a["sha"]) == (b["status"], b["range"], b["len"], b["sha"]):
            outcome = "identical"
        else:
            outcome = "differs"
        out.append((name, outcome, a, b))
    bfull = B.get(path, {"Range": "bytes=0-0"})
    same = (full["etag"], full["modified"]) == (bfull["etag"], bfull["modified"])
    out.append(("validators", "identical" if same else "differs", full, bfull))
    return out


def pct(xs, p):
    xs = sorted(xs)
    return xs[min(len(xs) - 1, int(len(xs) * p))] if xs else 0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("log", help="nginx access log ('-' = stdin)")
    ap.add_argument("--a", required=True, help="reference, e.g. http://pictshare")
    ap.add_argument("--b", required=True, help="candidate, e.g. http://mediaserver")
    ap.add_argument("--host", default="", help="Host header for both (default: from the URL)")
    ap.add_argument("--insecure", action="store_true", help="don't verify TLS certificates")
    ap.add_argument("--limit", type=int, default=0, help="replay at most this many paths")
    ap.add_argument("--shuffle", action="store_true", help="random sample instead of the first paths")
    ap.add_argument("--rate", type=float, default=5, help="requests per second per side (default 5)")
    ap.add_argument("--workers", type=int, default=2)
    ap.add_argument("--out", default="replay-diff.jsonl", help="non-identical paths, one JSON per line")
    ap.add_argument("--ranges", type=int, default=0, metavar="N",
                    help="also run the range / conditional checks on N of the videos (/raw)")
    args = ap.parse_args()

    with (sys.stdin if args.log == "-" else open(args.log, errors="replace")) as f:
        logged = paths_from_log(f)
    paths = list(logged)
    if args.shuffle:
        random.shuffle(paths)
    if args.limit:
        paths = paths[:args.limit]
    print(f"{len(logged)} unique GET paths in the log, replaying {len(paths)}", file=sys.stderr)

    A = Side(args.a, args.host, args.insecure, args.rate)
    B = Side(args.b, args.host, args.insecure, args.rate)
    counts = collections.defaultdict(collections.Counter)
    ms = {"a": [], "b": []}
    done = 0
    lock = threading.Lock()

    def one(path):
        b = B.get(path)
        a = A.get(path)
        return path, a, b

    with open(args.out, "w") as out, ThreadPoolExecutor(args.workers) as ex:
        for path, a, b in ex.map(one, paths):
            outcome = "error" if not a["status"] or not b["status"] else compare(a, b)
            with lock:
                counts[shape(path)][outcome] += 1
                ms["a"].append(a["ms"])
                ms["b"].append(b["ms"])
                if outcome not in ("identical", "same"):
                    out.write(json.dumps({"path": path, "outcome": outcome, "logged": logged[path], "a": a, "b": b}) + "\n")
                done += 1
                if done % 500 == 0:
                    print(f"  {done}/{len(paths)}", file=sys.stderr)

        ranges = collections.defaultdict(collections.Counter)
        if args.ranges:
            videos = sorted({seg for p in logged for seg in urllib.parse.urlsplit(p).path.split("/")
                             if HASH_RE.match(seg) and seg.endswith(".mp4")})
            if args.shuffle:
                random.shuffle(videos)
            videos = videos[:args.ranges]
            print(f"range checks on {len(videos)} videos", file=sys.stderr)
            for checks in ex.map(lambda v: [(f"/{v}/raw",) + c for c in range_checks(f"/{v}/raw", A, B)], videos):
                for path, name, outcome, a, b in checks:
                    ranges[name][outcome] += 1
                    if outcome != "identical":
                        out.write(json.dumps({"path": path, "check": name, "outcome": outcome, "a": a, "b": b}) + "\n")

    outcomes = ["identical", "same", "type-only", "same-size", "image-size", "type", "status", "location", "body", "error"]
    used = [o for o in outcomes if any(c[o] for c in counts.values())]
    rows = sorted(counts.items(), key=lambda kv: -sum(kv[1].values()))
    w = max([len(s) for s, _ in rows] + [5])
    print(f"{'shape':<{w}}  " + "  ".join(f"{o:>10}" for o in used))
    total = collections.Counter()
    for s, c in rows:
        total.update(c)
        print(f"{s:<{w}}  " + "  ".join(f"{c[o]:>10}" for o in used))
    print(f"{'total':<{w}}  " + "  ".join(f"{total[o]:>10}" for o in used))
    for side in ("a", "b"):
        print(f"latency {side}: p50 {pct(ms[side], .5)} ms, p95 {pct(ms[side], .95)} ms, max {max(ms[side], default=0)} ms")
    if ranges:
        print(f"\n{'range check':<20}  {'identical':>10}  {'differs':>10}  {'error':>10}")
        for name, _ in RANGE_CHECKS + [("validators", None)]:
            c = ranges[name]
            print(f"{name:<20}  {c['identical']:>10}  {c['differs']:>10}  {c['error']:>10}")
    print(f"details of everything not identical: {args.out}")


if __name__ == "__main__":
    main()
